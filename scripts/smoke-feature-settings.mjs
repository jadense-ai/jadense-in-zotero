/** 配置区真实 XPI 验收；隔离 profile 中检查两个宿主、偏好隔离与截图，不调用真实 Provider。 */
export async function verifyFeatureSettings({ Zotero, assert, waitFor, screenshot, report, findManager, findWindowContaining, config }) {
  const prefix = 'extensions.jadenseInZotero.', main = Zotero.getMainWindow()
  const get = key => Zotero.Prefs.get(prefix + key, true)
  const set = (key, value) => Zotero.Prefs.set(prefix + key, value, true)
  Zotero.Prefs.set(prefix + 'quickStartShown', true)
  main.openDialog('chrome://jadense-in-zotero/content/manager.xhtml?section=settings-features', 'jadense-settings-smoke', 'chrome,dialog=no,titlebar,resizable,width=1100,height=900', { zotero: Zotero, section: 'settings-features', pluginID: 'jadense-in-zotero@jadense.cn' })
  const manager = await waitFor(findManager, 'settings Manager')
  const doc = manager.document
  await waitFor(() => doc.querySelector('[data-translation-scope="document"] .jdx-select-trigger'), 'independent translation controls')
  if (doc.querySelector('#jadense-quick-start-dialog')?.open) doc.getElementById('jadense-quick-start-close').click()
  const root = doc.getElementById('jadense-settings-panel-features')
  // 比较真实宿主的计算样式，避免功能页再次偏离常规设置的行布局。
  doc.getElementById('jadense-settings-tab-general').click()
  assert(root.getBoundingClientRect().height === 0, 'Hidden feature settings remain visible')
  const generalStyle = manager.getComputedStyle(doc.querySelector('#jadense-settings-panel-general .jdx-feature-model-row'))
  const rowStyle = { padding: generalStyle.paddingBlock, border: generalStyle.borderBottomWidth, font: generalStyle.fontSize }
  doc.getElementById('jadense-settings-tab-features').click()
  for (const row of root.querySelectorAll('.jdx-feature-model-row:not([hidden]):not(.jdx-classification-settings)')) {
    const style = manager.getComputedStyle(row)
    assert(style.paddingBlock === rowStyle.padding && style.borderBottomWidth === rowStyle.border, 'Feature row differs from General settings: ' + row.className)
  }
  report.checks.push('settings-shared-general-row-style')
  // 快捷键和连接页必须复用常规页的实际尺寸，不仅检查类名。
  for (const name of ['shortcuts', 'connection']) {
    doc.getElementById(`jadense-settings-tab-${name}`).click()
    const panel = doc.getElementById(`jadense-settings-panel-${name}`)
    for (const row of panel.querySelectorAll('.jdx-feature-model-row')) {
      const style = manager.getComputedStyle(row)
      assert(style.paddingBlock === rowStyle.padding && style.borderBottomWidth === rowStyle.border, name + ' differs from General settings')
    }
    assert(panel.querySelector('.jdx-manager-settings-card').getBoundingClientRect().width >= panel.clientWidth - 2, name + ' has a separate width cap')
  }
  doc.getElementById('jadense-settings-tab-shortcuts').click()
  const capture = doc.getElementById('jadense-shortcut-capture-input')
  const shortcutPref = prefix + 'readerShortcut.capture'
  capture.focus()
  capture.dispatchEvent(new manager.KeyboardEvent('keydown', { key: 'y', code: 'KeyY', ctrlKey: true, shiftKey: true, bubbles: true }))
  assert(!doc.getElementById('jadense-shortcut-capture-save').disabled, 'Recorded shortcut cannot save')
  doc.getElementById('jadense-shortcut-capture-save').click()
  assert(Zotero.Prefs.get(shortcutPref) === 'Ctrl+Shift+Y', 'Shortcut did not save')
  doc.getElementById('jadense-shortcut-capture-disable').click()
  assert(Zotero.Prefs.get(shortcutPref) === 'Ctrl+Shift+Y', 'Disable changed saved shortcut before Save')
  doc.getElementById('jadense-shortcut-capture-save').click()
  assert(Zotero.Prefs.get(shortcutPref) === '', 'Disable did not save')
  doc.getElementById('jadense-shortcut-capture-reset').click()
  doc.getElementById('jadense-shortcut-capture-save').click()
  assert(Zotero.Prefs.get(shortcutPref) === 'Mod+Alt+S', 'Restore default did not save')
  doc.getElementById('jadense-settings-tab-connection').click()
  const token = doc.getElementById('jadense-manager-token-input')
  doc.getElementById('jadense-manager-token-edit').click()
  assert(doc.activeElement === token && token.labels.length === 1 && token.type === 'password', 'Token edit lacks focus, label or masking')
  token.value = 'synthetic-cancelled-draft'
  doc.getElementById('jadense-manager-token-cancel').click()
  assert(token.value === '' && doc.getElementById('jadense-manager-token-edit-row').hidden, 'Cancel left token draft visible')
  report.checks.push('settings-shortcut-connection-shared-layout', 'settings-shortcut-save-disable-reset', 'settings-token-labelled-edit-cancel')
  doc.getElementById('jadense-settings-tab-features').click()
  const openGroup = (scope, key) => { scope.querySelector(`[data-settings-target="${key}"]`).click() }
  const choose = async (win, container, text) => {
    const group = container.closest('[data-settings-task]')
    if (group) openGroup(group.closest('.jdx-settings-layout'), group.dataset.settingsTask)
    container.querySelector('.jdx-select-trigger').click()
    const option = await waitFor(() => [...container.querySelectorAll('[role="option"]')].find(node => node.textContent.includes(text)), 'option ' + text)
    option.click()
  }
  assert(root.querySelectorAll('[data-settings-task]:not([hidden])').length === 1, 'Multiple feature details visible')
  const lastNav = root.querySelector('[data-settings-target="organization"]')
  lastNav.focus(); lastNav.dispatchEvent(new manager.KeyboardEvent('keydown', { key: 'Home', bubbles: true }))
  assert(doc.activeElement.dataset.settingsTarget === 'chat', 'Directory Home navigation failed')
  openGroup(root, 'figure')
  assert(root.querySelector('[data-settings-task="figure"]').getBoundingClientRect().height < 220, 'Single-field image settings inflated')
  assert(root.querySelector('[data-settings-task="selection"]').getBoundingClientRect().height === 0, 'Hidden feature occupies space')
  openGroup(root, 'organization')
  const draftKey = root.querySelector('[data-classification-settings-host] input[type="password"]'), previousDraft = draftKey.value
  draftKey.value = 'synthetic-unsaved-settings-draft'
  openGroup(root, 'chat'); openGroup(root, 'organization')
  assert(draftKey.value === 'synthetic-unsaved-settings-draft', 'Directory switch lost unsaved draft')
  draftKey.value = previousDraft
  openGroup(root, 'figure'); root.querySelector('[data-settings-task="figure"] .jdx-settings-link').click()
  assert(!root.querySelector('[data-settings-task="chat"]').hidden && doc.activeElement.id === 'jadense-auto-follow-chat-model', 'Model follow link failed')
  report.checks.push('settings-directory-keyboard-single-detail-and-draft', 'settings-model-follow-link')
  const groups = [...root.querySelectorAll('[data-settings-task]')].map(node => node.dataset.settingsTask)
  assert(groups.join() === 'chat,selection,figure,pdf-translation,document,analysis,organization', 'Task groups are not ordered')
  assert(root.querySelectorAll('[data-ocr-setting="document"]').length === 1 && !doc.querySelector('#jadense-settings-panel-ocr [data-ocr-setting="document"]'), 'Document switch not moved')
  assert(root.querySelectorAll('[data-ocr-setting="selection"]').length === 1, 'Selection switch duplicated')
  assert(root.querySelector('[data-classification-settings-host] input[type="password"]'), 'Classification settings missing')
  const english = config.appearanceLanguage === 'en-US'
  const selection = root.querySelector('[data-translation-scope="selection"]'), full = root.querySelector('[data-translation-scope="document"]')
  await choose(manager, selection.querySelector('[data-translation-setting="kind"]'), english ? 'Translation service' : '翻译接口')
  await choose(manager, selection.querySelector('[data-translation-setting="service"]'), 'Google')
  assert(JSON.parse(get('selectionTranslationInterface')).service === 'google', 'Selection service not saved')
  assert(JSON.parse(get('fullTranslationInterface')).kind === 'ai', 'Selection changed full translation')
  assert(selection.querySelector('[data-translation-ai-row]').hidden && !full.querySelector('[data-translation-ai-row]').hidden, 'Wrong AI model visibility')
  assert(selection.querySelector('details').hidden && !full.querySelector('details').open, 'Capacity should only appear for full AI translation, collapsed')
  assert(!root.querySelector('[data-pdf-engine-settings]'), 'Engine installer still in feature settings')
  const dependencies = doc.getElementById('jadense-settings-panel-ocr')
  assert(dependencies.querySelector('[data-external-dependency="ocr"]') && dependencies.querySelector('[data-external-dependency="layout"] [data-pdf-engine-settings]'), 'Dependency sections missing')
  assert(!dependencies.querySelector('[data-pdf-translation-mode]'), 'Translation scope belongs in feature settings')
  openGroup(root, 'pdf-translation')
  full.querySelector('[data-pdf-translation-settings] .jdx-manager-actions button').click()
  assert(!dependencies.hidden && doc.activeElement.closest('[data-pdf-engine-settings]'), 'Layout engine navigation failed')
  doc.getElementById('jadense-settings-tab-features').click()

  await choose(manager, full.querySelector('[data-pdf-translation-mode]'), english ? 'Full translation' : '完整翻译')
  assert(get('pdfTranslationMode') === 'full', 'Default PDF scope not saved')
  full.querySelector('[data-pdf-linked-scroll]').click()
  assert(get('pdfLinkedScroll') === false, 'Linked scroll not saved')
  report.checks.push('settings-task-groups', 'settings-independent-services', 'settings-ocr-location', 'settings-capacity-visibility')
  await Promise.resolve(Zotero.Utilities.Internal.openPreferences('jadense-in-zotero-preferences'))
  const preferences = await waitFor(() => findWindowContaining('jadense-in-zotero-preferences-pane'), 'native preferences')
  const native = preferences.document.querySelector('[data-settings-section="features"]')
  await waitFor(() => native.querySelector('[data-classification-settings-host] input'), 'native classification')
  assert(native.querySelectorAll('[data-settings-task]').length === 7, 'Native groups differ')
  assert(native.querySelector('[data-translation-scope="selection"] [data-translation-ai-row]').hidden, 'Native failed to read selection service')
  const follow = doc.getElementById('jadense-auto-follow-chat-model')
  openGroup(root, 'chat'); follow.click()
  await waitFor(() => !preferences.document.getElementById('jadense-in-zotero-auto-follow-chat-model').checked, 'global follow synchronization')
  assert(!full.querySelector('[data-translation-ai-row] .jdx-select-trigger').disabled, 'Independent full model locked')
  const nativeSelection = native.querySelector('[data-ocr-setting="selection"]')
  openGroup(native, 'selection'); nativeSelection.click()
  await waitFor(() => root.querySelector('[data-ocr-setting="selection"]').checked, 'selection OCR cross-window synchronization')
  openGroup(native, 'selection'); nativeSelection.click()
  const nativeFull = native.querySelector('[data-translation-scope="document"]')
  assert(!nativeFull.querySelector('[data-pdf-linked-scroll]').checked, 'Native linked-scroll preference not restored')
  await choose(preferences, nativeFull.querySelector('[data-pdf-translation-mode]'), english ? 'Concise translation' : '精简翻译')
  await waitFor(() => full.querySelector('[data-pdf-translation-mode]').textContent.includes(english ? 'Concise translation' : '精简翻译'), 'PDF scope cross-window sync')

  await choose(preferences, nativeFull.querySelector('[data-translation-setting="kind"]'), english ? 'Translation service' : '翻译接口')
  await waitFor(() => full.querySelector('[data-translation-ai-row]').hidden, 'full service cross-window synchronization')
  await choose(preferences, nativeFull.querySelector('[data-translation-setting="kind"]'), english ? 'AI generation' : 'AI 生成')
  report.checks.push('settings-native-sync', 'settings-follow-independent-controls', 'settings-selection-ocr-sync')
  const speed = root.querySelector('[data-translation-speed]'), nativeSpeed = native.querySelector('[data-translation-speed]')
  assert(speed && nativeSpeed, 'Translation speed settings missing in one host')
  openGroup(root, 'pdf-translation'); openGroup(native, 'pdf-translation')
  speed.open = nativeSpeed.open = true
  const rpm = await waitFor(() => speed.querySelector('[data-speed-field="rpm"]'), 'translation RPM settings')
  const speedRow = rpm.closest('[data-speed-address]'), speedAddress = speedRow.dataset.speedAddress
  const saveSpeed = [...speedRow.querySelectorAll('button')].find(node => /^(保存|Save)$/u.test(node.textContent))
  rpm.value = '30'; saveSpeed.click()
  assert(JSON.parse(get('translationSpeed'))[speedAddress].rpm === 30, 'RPM setting did not persist')
  await waitFor(() => [...nativeSpeed.querySelectorAll('[data-speed-address]')].find(node => node.dataset.speedAddress === speedAddress)?.querySelector('[data-speed-field="rpm"]').value === '30', 'speed cross-window synchronization')
  rpm.value = '-1'; saveSpeed.click()
  assert(JSON.parse(get('translationSpeed'))[speedAddress].rpm === 30, 'Invalid RPM replaced valid setting')
  ;[...speedRow.querySelectorAll('button')].find(node => /恢复默认|Restore defaults/u.test(node.textContent)).click()
  assert(JSON.parse(get('translationSpeed'))[speedAddress].rpm === 20, 'Speed defaults did not restore')
  report.checks.push('translation-speed-defaults-save-invalid-and-cross-window-sync')
  manager.focus(); await Zotero.Promise.delay(100)
  const configure = root.querySelector('[data-document-ocr-host] .jdx-ocr-summary button')
  openGroup(root, 'document'); configure.click()
  const ocrRoot = doc.getElementById('jadense-settings-panel-ocr')
  assert(!ocrRoot.hidden && root.hidden, 'OCR link did not switch tab')
  assert(![...ocrRoot.querySelectorAll('button')].some(node => /返回功能配置|Back to feature settings/u.test(node.textContent)), 'Redundant OCR back button remains')
  doc.getElementById('jadense-settings-tab-features').click()
  await screenshot('settings-focus-check', manager)
  assert(!root.hidden, 'OCR return focus: ' + doc.activeElement?.outerHTML?.slice(0, 250) + ' root hidden=' + root.hidden)
  report.checks.push('settings-ocr-navigation-focus')
  set('ocrEngine', 'custom')
  const documentOCR = root.querySelector('[data-ocr-setting="document"]')
  openGroup(root, 'document'); documentOCR.click()
  await waitFor(() => !documentOCR.disabled && !documentOCR.checked, 'unconfigured cloud OCR remains disabled')
  assert(!get('documentOCR'), 'Failed OCR check persisted enabled')
  assert(root.querySelector('[data-document-ocr-host] [role="status"]').textContent, 'OCR failure missing inline feedback')
  set('ocrEngine', 'local')
  report.checks.push('settings-ocr-check-failure-contained')
  const pause = () => Zotero.Promise.delay(250)
  for (const theme of ['light', 'dark']) {
    set('theme', theme); await pause()
    manager.resizeTo(1100, 950)
    doc.getElementById('jadense-settings-tab-general').click(); await pause()
    for (let node = root.parentElement; node; node = node.parentElement) node.scrollTop = 0
    await screenshot(`settings-general-${english ? 'en' : 'zh'}-${theme}`, manager)
    doc.getElementById('jadense-settings-tab-features').click()
    speed.open = true; openGroup(root, 'pdf-translation'); speed.scrollIntoView({ block: 'start' }); await pause()
    await screenshot(`translation-speed-${english ? 'en' : 'zh'}-${theme}`, manager)
    speed.open = false
    for (const name of ['chat', 'selection', 'figure', 'pdf-translation', 'document', 'analysis', 'organization']) {
      openGroup(root, name); root.querySelector(`[data-settings-task="${name}"]`).scrollIntoView({ block: 'start' });
      if (name === 'chat') for (let node = root.parentElement; node; node = node.parentElement) node.scrollTop = 0
      await pause()
      await screenshot(`settings-${english ? 'en' : 'zh'}-${theme}-${name}`, manager)
    }
    openGroup(native, 'selection'); native.querySelector('[data-settings-task="selection"]').scrollIntoView({ block: 'start' }); await pause()
    await screenshot(`settings-native-${english ? 'en' : 'zh'}-${theme}`, preferences)
    openGroup(root, 'document'); configure.click(); await pause(); await screenshot(`settings-ocr-${english ? 'en' : 'zh'}-${theme}`, manager); openGroup(dependencies, 'layout'); dependencies.querySelector('[data-external-dependency="layout"]').scrollIntoView({ block: 'start' }); await pause(); await screenshot(`settings-layout-${english ? 'en' : 'zh'}-${theme}`, manager); doc.getElementById('jadense-settings-tab-features').click()
    for (const name of ['shortcuts', 'connection']) {
      doc.getElementById(`jadense-settings-tab-${name}`).click(); await pause()
      await screenshot(`settings-${name}-${english ? 'en' : 'zh'}-${theme}`, manager)
    }
    doc.getElementById('jadense-settings-tab-ai').click(); await pause()
    const byok = doc.getElementById('jadense-settings-panel-ai')
    assert(byok.scrollWidth <= byok.clientWidth + 2, 'BYOK settings overflow')
    await screenshot(`settings-byok-${english ? 'en' : 'zh'}-${theme}`, manager)
    doc.getElementById('jadense-settings-tab-connection').click()
    doc.getElementById('jadense-manager-token-edit').click(); await pause()
    await screenshot(`settings-token-edit-${english ? 'en' : 'zh'}-${theme}`, manager)
    doc.getElementById('jadense-manager-token-cancel').click()
    doc.getElementById('jadense-settings-tab-features').click()
  }
  manager.resizeTo(720, 800); set('theme', 'light'); await pause()
  speed.open = true; openGroup(root, 'pdf-translation'); speed.scrollIntoView({ block: 'start' }); await pause()
  assert(root.scrollWidth <= root.clientWidth + 2, 'Translation speed settings overflow')
  await screenshot(`translation-speed-${english ? 'en' : 'zh'}-compact`, manager)
  openGroup(root, 'selection'); root.querySelector('[data-settings-task="selection"]').scrollIntoView({ block: 'start' }); await pause()
  assert(root.scrollWidth <= root.clientWidth + 2, 'Compact settings overflow horizontally')
  await screenshot(`settings-${english ? 'en' : 'zh'}-compact`, manager)
  set('fontScale', '150'); await pause()
  for (const name of ['shortcuts', 'connection']) {
    doc.getElementById(`jadense-settings-tab-${name}`).click(); await pause()
    const panel = doc.getElementById(`jadense-settings-panel-${name}`)
    assert(panel.scrollWidth <= panel.clientWidth + 2, name + ' overflows at 150% in a compact window')
    for (const row of panel.querySelectorAll('.jdx-feature-model-row')) assert(manager.getComputedStyle(row).gridTemplateColumns.split(' ').length === 1, name + ' did not stack in a compact window')
    await screenshot(`settings-${name}-${english ? 'en' : 'zh'}-compact-150`, manager)
  }
  doc.getElementById('jadense-settings-tab-features').click()
  assert(root.scrollWidth <= root.clientWidth + 2, 'Scaled settings overflow horizontally')
  await screenshot(`settings-${english ? 'en' : 'zh'}-compact-150`, manager)
  openGroup(native, 'document'); native.querySelector('[data-settings-task="document"]').scrollIntoView({ block: 'start' }); await pause()
  await screenshot(`settings-native-${english ? 'en' : 'zh'}-150`, preferences)
  doc.getElementById('jadense-settings-tab-ai').click(); await pause()
  const compactByok = doc.getElementById('jadense-settings-panel-ai')
  assert(compactByok.scrollWidth <= compactByok.clientWidth + 2, 'BYOK overflows at 150% in compact window')
  assert(manager.getComputedStyle(compactByok.querySelector('.jdx-manager-byok-layout')).gridTemplateColumns.split(' ').length === 1, 'Compact BYOK provider/editor failed to stack')
  await screenshot(`settings-byok-${english ? 'en' : 'zh'}-compact-150`, manager)
  doc.getElementById('jadense-settings-tab-features').click()
  set('fontScale', '100')
  const trigger = selection.querySelector('[data-translation-setting="kind"] .jdx-select-trigger')
  trigger.focus(); trigger.dispatchEvent(new manager.KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true }))
  assert(trigger.getAttribute('aria-expanded') === 'true', 'Keyboard did not open translation selector')
  trigger.dispatchEvent(new manager.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))
  assert(trigger.getAttribute('aria-expanded') === 'false', 'Escape did not close translation selector')
  report.checks.push('settings-compact-no-overflow', 'settings-two-hosts-light-dark', 'settings-font-scale-150', 'settings-keyboard-selector')
  assert(!get('documentOCR') && !get('ocrSelection'), 'Opening settings enabled OCR')
  assert(Zotero.__jadenseDocumentJobs.list().length === 0, 'Settings created document tasks')
  openGroup(root, 'document'); configure.click()
  set('ocrEngine', 'glm')
  const key = await waitFor(() => ocrRoot.querySelector('[data-ocr-setting="key"]'), 'cloud key input')
  await waitFor(() => ocrRoot.querySelector('[data-ocr-setting="model"]').value === 'glm-ocr', 'GLM settings loaded')
  key.value = 'synthetic-persistent-ocr-key'
  ocrRoot.querySelector('.jdx-cloud-ocr-consent input').checked = true
  ;[...ocrRoot.querySelectorAll('button')].find(node => /保存并使用|Save and use/u.test(node.textContent)).click()
  await waitFor(() => /重启后无需|remains available after restart/u.test(ocrRoot.textContent), 'persistent OCR save')
  report.checks.push('settings-ocr-key-persisted')
  // 登录管理器延迟写盘；外层强制结束进程前留出原生存储落盘时间。
  await Zotero.Promise.delay(3000)
  set('featureSettingsSmokeSaved', true)
  // 外层用强制关闭模拟冷启动，先落盘，避免把 Gecko 的异步写入误判为设置丢失。
  main.Services.prefs.savePrefFile(null)
  assert(!(report.screenshotWarnings?.length), 'Screenshot capture failed')
}

export function verifyFeatureSettingsRestart({ Zotero, assert, report }) {
  const get = key => Zotero.Prefs.get('extensions.jadenseInZotero.' + key, true)
  assert(get('featureSettingsSmokeSaved') === true, 'Missing saved smoke state')
  const logins = Zotero.getMainWindow().Services.logins.findLogins('chrome://jadense-in-zotero', null, 'glm:https://open.bigmodel.cn/api/paas/v4/layout_parsing')
  assert(logins.some(login => login.password === 'synthetic-persistent-ocr-key'), 'Restart lost OCR credential')
  report.checks.push('settings-ocr-key-cold-restart')
  assert(JSON.parse(get('selectionTranslationInterface')).service === 'google', 'Restart lost selection settings')
  assert(JSON.parse(get('fullTranslationInterface')).kind === 'ai', 'Restart lost full translation settings')
  assert(Zotero.Prefs.get('extensions.jadenseInZotero.autoFollowChatModel') === false && !get('ocrSelection'), 'Restart lost follow/OCR settings')
  report.checks.push('settings-cold-restart-preserves-independent-preferences')
}
